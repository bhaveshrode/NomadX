from abc import ABC, abstractmethod
from typing import Optional, List
from datetime import datetime
from .receivable import Receivable
from .value_objects import ReceivableId, InvoiceId, CustomerId, ReceivableReference
from ..organization.value_objects import OrganizationId


class IReceivableRepository(ABC):
    """
    Contract representing the domain persistence gateway for Receivable aggregates.
    """
    @abstractmethod
    async def get_by_id(self, id: ReceivableId, lock: bool = False) -> Optional[Receivable]:
        """Loads a Receivable by its unique ID, optionally acquiring a database lock."""
        pass

    async def get_by_reference(self, reference: ReceivableReference) -> Optional[Receivable]:
        """Loads a Receivable by its unique reference."""
        raise NotImplementedError()

    async def find_by_invoice(self, invoice_id: InvoiceId) -> Optional[Receivable]:
        """Loads the Receivable generated by a specific Invoice ID."""
        raise NotImplementedError()

    async def find_by_customer(self, customer_id: CustomerId) -> List[Receivable]:
        """Retrieves all Receivables belonging to a specific Customer ID."""
        raise NotImplementedError()

    async def find_outstanding(self, organization_id: OrganizationId) -> List[Receivable]:
        """Retrieves all outstanding Receivables (outstanding amount > 0) belonging to an organization."""
        raise NotImplementedError()

    async def find_overdue(self, organization_id: OrganizationId, current_time: datetime) -> List[Receivable]:
        """Retrieves all overdue Receivables belonging to an organization."""
        raise NotImplementedError()

    @abstractmethod
    async def save(self, receivable: Receivable) -> None:
        """Saves or merges the state of the Receivable aggregate in persistent storage."""
        pass

    @abstractmethod
    async def delete(self, id: ReceivableId) -> None:
        """Deletes a Receivable from storage by its ID."""
        pass

    # Old methods retained for backward compatibility:
    @abstractmethod
    async def find_by_invoice_id(self, invoice_id: InvoiceId) -> Optional[Receivable]:
        pass

    @abstractmethod
    async def find_by_customer_id(self, customer_id: CustomerId) -> List[Receivable]:
        pass

    @abstractmethod
    async def find_by_organization(self, organization_id: OrganizationId) -> List[Receivable]:
        pass

    @abstractmethod
    async def find_outstanding_candidates(self, organization_id: OrganizationId, current_time: datetime) -> List[Receivable]:
        pass

    @abstractmethod
    async def get_aging_summary(self, organization_id: OrganizationId, current_time: datetime) -> dict:
        pass


from .collection_action import CollectionAction, CollectionActionId

class ICollectionActionRepository(ABC):
    """
    Contract representing the domain persistence gateway for CollectionAction entities.
    """
    @abstractmethod
    async def save(self, action: CollectionAction) -> None:
        """Saves a CollectionAction entity."""
        pass

    @abstractmethod
    async def find_by_id(self, action_id: CollectionActionId) -> Optional[CollectionAction]:
        """Finds a CollectionAction by its unique ID."""
        pass

    @abstractmethod
    async def claim_pending_actions(self, limit: int, current_time: datetime) -> List[CollectionAction]:
        """Claims a list of pending/failed scheduled collection actions with FOR UPDATE SKIP LOCKED."""
        pass

    @abstractmethod
    async def find_by_idempotency_key(self, organization_id: OrganizationId, idempotency_key: str) -> Optional[CollectionAction]:
        """Finds a CollectionAction by its idempotency key within an organization."""
        pass

    @abstractmethod
    async def cancel_pending_actions(self, receivable_id: ReceivableId) -> None:
        """Cancels all pending/processing/retryable collection actions for a receivable."""
        pass

